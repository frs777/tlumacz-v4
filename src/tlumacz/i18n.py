class I18n:
    """Udostępnia teksty lokalizacyjne dla bieżącego języka."""

    def __init__(self, language: str = "pl") -> None:
        self._language = language if language in TRANSLATIONS else "pl"

    @property
    def language(self) -> str:
        return self._language

    @language.setter
    def language(self, value: str) -> None:
        self._language = value if value in TRANSLATIONS else "pl"

    def t(self, key: str, **kwargs: object) -> str:
        text = TRANSLATIONS[self._language].get(key, PL.get(key, key))
        if kwargs:
            try:
                text = text.format(**kwargs)
            except (KeyError, ValueError, IndexError):
                pass
        return text


_i18n = I18n()


def set_language(language: str) -> None:
    """Ustawia globalny język aplikacji; nieznany kod wraca do polskiego."""
    global _i18n
    _i18n = I18n(language)


def get_language() -> str:
    """Zwraca aktualny język aplikacji."""
    return _i18n.language


def t(key: str, **kwargs: object) -> str:
    """Zwraca tekst dla bieżącego języka."""
    return _i18n.t(key, **kwargs)


